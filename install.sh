#!/usr/bin/env bash
# Installer for the opencode-tokens-usage CLI plugin.
#
# Verified mechanism on OpenCode v2.1.4 (2026-10-24): plugins auto-load from
# directories under ~/.config/opencode/plugins/ (each directory's index.ts is
# the server entry; a tui.tsx at the directory root marks the TUI feature).
# Config-file `plugins` entries (cli.json or opencode.json) with local paths
# were tested and are NOT applied by 2.1.4 — this installer therefore deploys
# a small directory with shim files that re-export the repo sources.
#
# Usage:
#   ./install.sh [--target DIR] [--dry-run] [--uninstall]
#
# Defaults:
#   target = ${XDG_CONFIG_HOME:-$HOME/.config}/opencode/plugins/tokens-usage
#
# Note: the shims use absolute paths into this repo. Moving the repo breaks
# the install — re-run ./install.sh after moving.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DEFAULT_TARGET="${XDG_CONFIG_HOME:-$HOME/.config}/opencode/plugins/tokens-usage"
TARGET="$DEFAULT_TARGET"

DRY_RUN=0
UNINSTALL=0

while [[ $# -gt 0 ]]; do
  case "$1" in
    --target)   TARGET="$2"; shift 2 ;;
    --dry-run)  DRY_RUN=1; shift ;;
    --uninstall) UNINSTALL=1; shift ;;
    -h|--help)  sed -n '2,17p' "$0"; exit 0 ;;
    *) echo "Unknown option: $1 (see --help)" >&2; exit 1 ;;
  esac
done

if command -v realpath >/dev/null 2>&1; then
  REPO="$(realpath "$SCRIPT_DIR")"
else
  REPO="$(cd "$SCRIPT_DIR" && pwd)"
fi

echo "Repo:          $REPO"
echo "Install target: $TARGET"

if [[ ! -f "$REPO/src/tui.tsx" || ! -f "$REPO/src/index.ts" ]]; then
  echo "error: plugin sources not found next to install.sh (expected src/tui.tsx and src/index.ts)" >&2
  exit 1
fi

# Warn about stale registrations from earlier attempts (double-load risk).
for cfg in \
  "${XDG_CONFIG_HOME:-$HOME/.config}/opencode/cli.json" \
  "${XDG_CONFIG_HOME:-$HOME/.config}/opencode/opencode.json"; do
  if [[ -f "$cfg" ]] && grep -q "opencode-context-info\|opencode-tokens-usage" "$cfg" 2>/dev/null; then
    cat >&2 <<EOF
WARNING: this repo is referenced in $cfg.
Config-file plugin entries with local paths are not applied by v2.1.4 and can
cause double-loading if that changes in a future version. Consider removing
the entry.
EOF
  fi
done

write_shims() {
  mkdir -p "$TARGET"
  cat > "$TARGET/index.ts" <<EOF
// Generated by opencode-context-info/install.sh — do not edit.
// Directory plugins load only index.ts as the server entry.
export { default } from "$REPO/src/index.ts"
EOF
  cat > "$TARGET/tui.tsx" <<EOF
// Generated by opencode-context-info/install.sh — do not edit.
// A tui.tsx at the directory root marks the TUI feature for the CLI.
export { default } from "$REPO/src/tui.tsx"
EOF
}

if [[ "$UNINSTALL" == "1" ]]; then
  if [[ ! -d "$TARGET" ]]; then
    echo "Nothing to uninstall: $TARGET does not exist."
    exit 0
  fi
  if [[ "$DRY_RUN" == "1" ]]; then
    echo "[dry-run] would remove $TARGET"
    exit 0
  fi
  rm -rf "$TARGET"
  echo "Removed $TARGET"
  echo "Done. Restart OpenCode."
  exit 0
fi

if [[ "$DRY_RUN" == "1" ]]; then
  echo "[dry-run] would write shims into $TARGET:"
  echo "  index.ts -> $REPO/src/index.ts"
  echo "  tui.tsx  -> $REPO/src/tui.tsx"
  exit 0
fi

write_shims
echo "Wrote shims:"
echo "  $TARGET/index.ts -> $REPO/src/index.ts"
echo "  $TARGET/tui.tsx  -> $REPO/src/tui.tsx"
echo "Done. Restart OpenCode (or run /reload) and use /tokens_usage."
